// Validates the fragment hash implementation against the reference hash
// provided in Figure 4 of draft-prz-lsr-ash-packets-00.
#[test]
fn test_fragment_hash1() {
    let lsp_id = LspId::from([0x01, 0x01, 0x01, 0x01, 0x00, 0x00, 0x01, 0x01]);
    assert_eq!(
        ash_fragment_hash(&lsp_id, 0x0001, 0x0001, 512),
        0x6eb348f808c9ae4e
    );
}
